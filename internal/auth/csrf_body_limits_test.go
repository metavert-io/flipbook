// oversizedBody is larger than any limit under test; the 185 MB matches the
// anonymous request that was read in full by production before this fix.
const oversizedBody = 185 << 20

// repeatReader yields the same byte forever without allocating, so tests can
// offer multi-hundred-megabyte bodies cheaply.
type repeatReader byte

func (b repeatReader) Read(p []byte) (int, error) {
	for index := range p {
		p[index] = byte(b)
	}
	return len(p), nil
}

type countingReader struct {
	reader io.Reader
	read   int64
}

func (c *countingReader) Read(p []byte) (int, error) {
	n, err := c.reader.Read(p)
	c.read += int64(n)
	return n, err
}

type multipartField struct {
	name  string
	value string
	file  bool
	// size, when set, streams that many generated bytes as the part body
	// instead of value.
	size int64
}

func streamedMultipart(t *testing.T, fields ...multipartField) (*countingReader, string) {
	t.Helper()
	var buffer bytes.Buffer
	writer := multipart.NewWriter(&buffer)
	var readers []io.Reader
	for _, field := range fields {
		var part io.Writer
		var err error
		if field.file {
			part, err = writer.CreateFormFile(field.name, "document.pdf")
		} else {
			part, err = writer.CreateFormField(field.name)
		}
		if err != nil {
			t.Fatal(err)
		}
		if field.size > 0 {
			readers = append(readers, bytes.NewReader(bytes.Clone(buffer.Bytes())), io.LimitReader(repeatReader('A'), field.size))
			buffer.Reset()
			continue
		}
		if _, err := io.WriteString(part, field.value); err != nil {
			t.Fatal(err)
		}
	}
	if err := writer.Close(); err != nil {
		t.Fatal(err)
	}
	readers = append(readers, bytes.NewReader(bytes.Clone(buffer.Bytes())))
	return &countingReader{reader: io.MultiReader(readers...)}, writer.FormDataContentType()
}

// isolatedTempDir points multipart spooling at an empty directory so a test
// can prove nothing was written to disk.
func isolatedTempDir(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	t.Setenv("TMPDIR", dir)
	return dir
}

func assertNoTempFiles(t *testing.T, dir string) {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 0 {
		t.Fatalf("request body was spooled to disk: %d temp file(s), first %q", len(entries), entries[0].Name())
	}
}

func csrfBodyRequest(target string, body io.Reader, contentType string, withCookie bool) *http.Request {
	r := httptest.NewRequest(http.MethodPost, target, body)
	r.RemoteAddr = "203.0.113.10:43210"
	r.Header.Set("Content-Type", contentType)
	r.Header.Set("Origin", "http://"+r.Host)
	if withCookie {
		r.AddCookie(&http.Cookie{Name: CSRFCookieName, Value: testCSRFCookie()})
	}
	return r
}

func TestCSRFMiddlewareReadsOnlyABoundedPrefixOfOversizedBodies(t *testing.T) {
	a := testAuth(t, newFakeStore(), Options{})
	token := a.csrfToken(testCSRFCookie(), "")
	handler := a.CSRFMiddleware(http.HandlerFunc(func(http.ResponseWriter, *http.Request) {
		t.Fatal("request without a usable CSRF token reached the handler")
	}))
	urlencoded := func() (*countingReader, string) {
		return &countingReader{reader: io.MultiReader(strings.NewReader("note="), repeatReader('a'))}, "application/x-www-form-urlencoded"
	}
	for name, test := range map[string]struct {
		body    func() (*countingReader, string)
		status  int
		maxRead int64
	}{
		"multipart without token": {
			body: func() (*countingReader, string) {
				return streamedMultipart(t, multipartField{name: "title", value: "x"}, multipartField{name: "file", file: true, size: oversizedBody})
			},
			status: http.StatusForbidden, maxRead: maxCSRFMultipartScan,
		},
		"multipart token after file": {
			body: func() (*countingReader, string) {
				return streamedMultipart(t, multipartField{name: "file", file: true, size: oversizedBody}, multipartField{name: CSRFFormField, value: token})
			},
			status: http.StatusForbidden, maxRead: maxCSRFMultipartScan,
		},
		"multipart token after huge field": {
			body: func() (*countingReader, string) {
				return streamedMultipart(t, multipartField{name: "padding", size: oversizedBody}, multipartField{name: CSRFFormField, value: token})
			},
			status: http.StatusForbidden, maxRead: maxCSRFMultipartScan,
		},
		"urlencoded over limit": {
			body:   urlencoded,
			status: http.StatusRequestEntityTooLarge, maxRead: maxCSRFFormBytes + 1,
		},
	} {
		t.Run(name, func(t *testing.T) {
			tempDir := isolatedTempDir(t)
			body, contentType := test.body()
			recorder := httptest.NewRecorder()
			handler.ServeHTTP(recorder, csrfBodyRequest("/admin/upload", body, contentType, true))
			if recorder.Code != test.status {
				t.Fatalf("status = %d, want %d", recorder.Code, test.status)
			}
			if body.read > test.maxRead {
				t.Fatalf("CSRF check read %d bytes, limit %d", body.read, test.maxRead)
			}
			assertNoTempFiles(t, tempDir)
		})
	}
}

func TestCSRFMiddlewareLeavesUploadBodyForHandler(t *testing.T) {
	a := testAuth(t, newFakeStore(), Options{})
	token := a.csrfToken(testCSRFCookie(), "")
	// Larger than the scan window, so the handler must see the replayed
	// prefix stitched to the unread remainder.
	document := bytes.Repeat([]byte("%PDF-1.7 flipbook "), (3*maxCSRFMultipartScan)/18)
	for name, inHeader := range map[string]bool{"header token": true, "form token": false} {
		t.Run(name, func(t *testing.T) {
			var body bytes.Buffer
			writer := multipart.NewWriter(&body)
			if !inHeader {
				if err := writer.WriteField(CSRFFormField, token); err != nil {
					t.Fatal(err)
				}
			}
			if err := writer.WriteField("title", "Quarterly report"); err != nil {
				t.Fatal(err)
			}
			part, err := writer.CreateFormFile("file", "report.pdf")
			if err != nil {
				t.Fatal(err)
			}
			if _, err := part.Write(document); err != nil {
				t.Fatal(err)
			}
			if err := writer.Close(); err != nil {
				t.Fatal(err)
			}
			original := bytes.Clone(body.Bytes())
			request := csrfBodyRequest("/admin/upload", &body, writer.FormDataContentType(), true)
			if inHeader {
				request.Header.Set(CSRFHeaderName, token)
			}
			reached := false
			handler := a.CSRFMiddleware(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				reached = true
				received, err := io.ReadAll(http.MaxBytesReader(w, r.Body, int64(len(original))+1))
				if err != nil {
					t.Fatal(err)
				}
				if !bytes.Equal(received, original) {
					t.Fatalf("handler received %d bytes that differ from the %d sent", len(received), len(original))
				}
				w.WriteHeader(http.StatusNoContent)
			}))
			recorder := httptest.NewRecorder()
			handler.ServeHTTP(recorder, request)
			if !reached || recorder.Code != http.StatusNoContent {
				t.Fatalf("valid upload was rejected: %d %s", recorder.Code, recorder.Body.String())
			}
		})
	}
}

func TestAuthFormsCapBodiesBeforeAuthentication(t *testing.T) {
	store := newFakeStore()
	addUser(t, store, "editor@example.com", testPassword, models.RoleEditor)
	a := testAuth(t, store, Options{})
	token := a.csrfToken(testCSRFCookie(), "")
	for name, test := range map[string]struct {
		body       func() (*countingReader, string)
		withCookie bool
		status     int
	}{
		// The production repro: no cookie, so formSecurity mints one and the
		// CSRF check used to parse the whole body looking for a token.
		"anonymous multipart without cookie": {
			body: func() (*countingReader, string) {
				return streamedMultipart(t, multipartField{name: "username", value: "x"}, multipartField{name: "file", file: true, size: oversizedBody})
			},
			status: http.StatusForbidden,
		},
		// A valid token is free from GET /login; the handler's own parsing
		// must still be bounded.
		"multipart with valid token": {
			body: func() (*countingReader, string) {
				return streamedMultipart(t, multipartField{name: CSRFFormField, value: token}, multipartField{name: "file", file: true, size: oversizedBody})
			},
			withCookie: true, status: http.StatusRequestEntityTooLarge,
		},
		"urlencoded with valid token": {
			body: func() (*countingReader, string) {
				prefix := url.Values{CSRFFormField: {token}}.Encode() + "&username="
				return &countingReader{reader: io.MultiReader(strings.NewReader(prefix), io.LimitReader(repeatReader('a'), oversizedBody))}, "application/x-www-form-urlencoded"
			},
			withCookie: true, status: http.StatusRequestEntityTooLarge,
		},
	} {
		t.Run(name, func(t *testing.T) {
			tempDir := isolatedTempDir(t)
			body, contentType := test.body()
			recorder := httptest.NewRecorder()
			a.LoginSubmit(recorder, csrfBodyRequest("/login", body, contentType, test.withCookie))
			if recorder.Code != test.status {
				t.Fatalf("status = %d, want %d: %s", recorder.Code, test.status, recorder.Body.String())
			}
			if body.read > maxAuthFormBytes+1 {
				t.Fatalf("login read %d bytes, limit %d", body.read, maxAuthFormBytes)
			}
			assertNoTempFiles(t, tempDir)
		})
	}

	// The cap leaves ordinary sign-in alone.
	values := url.Values{"username": {"editor@example.com"}, "password": {testPassword}}
	recorder := httptest.NewRecorder()
	a.LoginSubmit(recorder, formRequest(a, http.MethodPost, "/login", values, ""))
	if recorder.Code != http.StatusSeeOther {
		t.Fatalf("normal login failed after body cap: %d %s", recorder.Code, recorder.Body.String())
	}
}
